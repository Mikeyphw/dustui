#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

version_name="$({ grep -E 'versionName = ' app/build.gradle.kts || true; } | sed -E 's/.*versionName = "([^"]+)".*/\1/' | head -n 1)"
if [[ -z "$version_name" ]]; then
  echo "Unable to read versionName from app/build.gradle.kts" >&2
  exit 1
fi

repo_root="$(cd "$root/.." && pwd)"
required_docs=(
  "$repo_root/CHANGELOG.md"
  "$repo_root/KNOWN_ISSUES.md"
  "$repo_root/RELEASE_CHECKLIST.md"
  "$repo_root/docs/ANDROID_PHASE15_FINAL_RC.md"
  "$repo_root/docs/ANDROID_PHASE24_CLEANING_INTELLIGENCE_FINAL_GATE.md"
  "$repo_root/docs/ANDROID_PHASE14_RELEASE_PACKAGING.md"
  "$repo_root/UI_UX_CONTRACT.md"
)
for doc in "${required_docs[@]}"; do
  if [[ ! -s "$doc" ]]; then
    echo "Missing final RC document: ${doc#$repo_root/}" >&2
    exit 1
  fi
done

bash -n scripts/device-certify.sh
bash -n scripts/install-smoke.sh
bash -n scripts/package-rc.sh
bash -n scripts/release-gate.sh
bash -n scripts/final-rc-gate.sh
bash -n scripts/cleaning-intelligence-gate.sh
python3 -m py_compile scripts/cleaning-intelligence-audit.py

if [[ "${DUSTUI_SKIP_RELEASE_GATE:-0}" != "1" ]]; then
  bash scripts/release-gate.sh
else
  DUSTUI_SKIP_BUILD=1 bash scripts/package-rc.sh
fi

rc_dir="build/release-candidate/dustui-$version_name"
if [[ ! -s "$rc_dir/manifest.json" || ! -s "$rc_dir/SHA256SUMS" ]]; then
  echo "Release-candidate bundle is missing manifest or checksums: $rc_dir" >&2
  exit 1
fi

status_root="build/final-rc/dustui-$version_name"
mkdir -p "$status_root"

known_issue_blockers=0
if grep -Eiq '^[-*] +\[(blocker|p0|p1)\]' "$repo_root/KNOWN_ISSUES.md"; then
  known_issue_blockers=1
fi

signed_release=false
if grep -q '"signedReleasePresent": true' "$rc_dir/manifest.json"; then
  signed_release=true
fi

smoke_evidence="${DUSTUI_SMOKE_EVIDENCE:-build/install-smoke}"
cert_archive="${DUSTUI_CERTIFICATION_ARCHIVE:-build/device-certification/device-certification.tar.gz}"
cleaning_evidence="${DUSTUI_CLEANING_EVIDENCE:-build/cleaning-intelligence/qualification.json}"
smoke_ready=false
cert_ready=false
cleaning_ready=false
if [[ -d "$smoke_evidence" ]]; then
  smoke_ready=true
fi
if [[ -s "$cert_archive" ]]; then cert_ready=true; fi
if [[ -s "$cleaning_evidence" ]] && grep -Eq '"ready"[[:space:]]*:[[:space:]]*true' "$cleaning_evidence"; then cleaning_ready=true; fi

ship_state="SHIP_WITH_WARNINGS"
if [[ "$known_issue_blockers" -eq 1 || "$cleaning_ready" != "true" ]]; then
  ship_state="DO_NOT_SHIP"
elif [[ "$signed_release" != "true" || "$smoke_ready" != "true" || "$cert_ready" != "true" ]]; then
  ship_state="SHIP_WITH_WARNINGS"
else
  ship_state="SHIP"
fi

cat > "$status_root/SHIP_STATUS.md" <<STATUS
# DustUI $version_name final RC status

Decision: $ship_state

Required evidence:
- Release gate: passed
- RC manifest: $rc_dir/manifest.json
- Checksums: $rc_dir/SHA256SUMS
- Signed release present: $signed_release
- Install smoke evidence present: $smoke_ready
- Device certification archive present: $cert_ready
- Cleaning intelligence qualification passed: $cleaning_ready
- Cleaning intelligence evidence: $cleaning_evidence
- Known blocker issues present: $([[ "$known_issue_blockers" -eq 1 ]] && echo true || echo false)

This file is generated by scripts/final-rc-gate.sh.
STATUS

cat > "$status_root/final-rc-manifest.json" <<JSON
{
  "app": "DustUI",
  "versionName": "$version_name",
  "decision": "$ship_state",
  "releaseCandidateManifest": "$rc_dir/manifest.json",
  "checksums": "$rc_dir/SHA256SUMS",
  "signedReleasePresent": $signed_release,
  "installSmokeEvidencePresent": $smoke_ready,
  "deviceCertificationArchivePresent": $cert_ready,
  "cleaningIntelligenceGatePassed": $cleaning_ready,
  "cleaningIntelligenceEvidence": "$cleaning_evidence",
  "knownIssueBlockersPresent": $([[ "$known_issue_blockers" -eq 1 ]] && echo true || echo false)
}
JSON

printf 'DustUI final RC status written to %s\n' "$status_root"
if [[ "$ship_state" == "DO_NOT_SHIP" ]]; then
  exit 1
fi
