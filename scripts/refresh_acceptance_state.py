#!/usr/bin/env python3
from __future__ import annotations
import argparse, json
from pathlib import Path
from audfix13_acceptance import ROOT, compute_state

STATE=ROOT/'migration/acceptance/v1/current_state.json'
GO_STATE=ROOT/'go/internal/qualification/acceptance_generated.go'

def render_go(state: dict) -> str:
    c=state['candidate']; q=state['qualification']
    return f'''// Code generated by scripts/refresh_acceptance_state.py; DO NOT EDIT.\npackage qualification\n\nconst AcceptanceStateSource = "migration/acceptance/v1/current_state.json"\nconst CandidateAcceptanceConverged = {str(bool(c['acceptance_converged'])).lower()}\nconst CandidateAcceptanceStatus = "{c['status']}"\nconst AcceptanceGateDQualified = {str(bool(q['gate_d_qualified'])).lower()}\n'''

def main()->int:
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); ap.add_argument('--json',action='store_true'); args=ap.parse_args()
    state=compute_state(ROOT)
    text=json.dumps(state,indent=2,sort_keys=True)+'\n'; got=render_go(state)
    if args.check:
        stale=[]
        if not STATE.is_file() or STATE.read_text()!=text: stale.append(str(STATE.relative_to(ROOT)))
        if not GO_STATE.is_file() or GO_STATE.read_text()!=got: stale.append(str(GO_STATE.relative_to(ROOT)))
        if stale:
            print('acceptance generated state is stale: '+', '.join(stale)); return 1
    else:
        STATE.parent.mkdir(parents=True,exist_ok=True); STATE.write_text(text)
        GO_STATE.parent.mkdir(parents=True,exist_ok=True); GO_STATE.write_text(got)
    if args.json: print(text,end='')
    else: print(f"Acceptance {state['candidate']['status']} (converged={state['candidate']['acceptance_converged']}); Gate D {state['qualification']['gate_d_status']}")
    return 0 if state['candidate']['acceptance_converged'] else 1
if __name__=='__main__': raise SystemExit(main())
