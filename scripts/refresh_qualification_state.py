#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path

from audfix01_core import compute_qualification, load_json

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / 'migration/qualification/v1/gate_d_evidence.json'
STATE = ROOT / 'migration/qualification/v1/current_state.json'
GO_STATE = ROOT / 'go/internal/qualification/state_generated.go'


def render_go(state: dict) -> str:
    gate = state['gate_d']
    obs = state['observed_repository']
    missing = gate['nonpassing_nodes'] + gate['missing_node_definitions'] + gate['invalid_binding_nodes']
    missing = sorted(set(missing))
    items = ''.join(f'\t"{x}",\n' for x in missing).rstrip('\n')
    required_items = ''.join(f'\t"{x}",\n' for x in gate['required_nodes']).rstrip('\n')
    return f'''// Code generated by scripts/refresh_qualification_state.py; DO NOT EDIT.\npackage qualification\n\nconst StateSource = "migration/qualification/v1/current_state.json"\nconst EvidenceRegistry = "migration/qualification/v1/gate_d_evidence.json"\nconst GateDQualified = {str(bool(gate['qualified'])).lower()}\nconst GateDStatus = "{gate['status']}"\nconst GateDReason = "{gate['reason']}"\nconst OV14Status = "{state['ov14']['status']}"\nconst GateEStatus = "{state['gate_e']['status']}"\nconst LegacyPythonTextualPresent = {str(bool(obs['legacy_python_textual_present'])).lower()}\nconst PythonTextualOraclePresent = {str(bool(obs['python_textual_oracle_present'])).lower()}\nconst RoomArtifactsPresent = {str(bool(obs['room_artifacts_present'])).lower()}\nconst LegacyNavigationPresent = {str(bool(obs['legacy_navigation_present'])).lower()}\nconst AndroidGoProcessBindingPresent = {str(bool(obs['android_go_process_binding_present'])).lower()}\nconst AndroidGoPackagingPresent = {str(bool(obs['android_go_packaging_present'])).lower()}\nconst GoSQLiteImplementationPresent = {str(bool(obs['go_sqlite_implementation_present'])).lower()}\nconst GenericToolingDuplicationPresent = {str(bool(obs['generic_tooling_duplication_paths'] or obs['release_kotlin_authority_paths'])).lower()}\n\nvar RequiredEvidenceNodes = []string{{\n{required_items}\n}}\n\nvar MissingRequiredEvidence = []string{{\n{items}\n}}\n'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--json', action='store_true')
    args = ap.parse_args()
    registry = load_json(REGISTRY)
    state = compute_qualification(ROOT, registry)
    state_text = json.dumps(state, indent=2, sort_keys=True) + '\n'
    go_text = render_go(state)
    if args.check:
        bad=[]
        if not STATE.is_file() or STATE.read_text() != state_text: bad.append(str(STATE.relative_to(ROOT)))
        if not GO_STATE.is_file() or GO_STATE.read_text() != go_text: bad.append(str(GO_STATE.relative_to(ROOT)))
        if bad:
            print('qualification generated state is stale: ' + ', '.join(bad))
            return 1
    else:
        STATE.write_text(state_text)
        GO_STATE.parent.mkdir(parents=True, exist_ok=True)
        GO_STATE.write_text(go_text)
    if args.json:
        print(state_text, end='')
    else:
        print(f"Gate D {state['gate_d']['status']} (qualified={state['gate_d']['qualified']}); OV14 {state['ov14']['status']}; Gate E {state['gate_e']['status']}")
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
